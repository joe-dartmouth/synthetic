"""`python -m bko.evaluate shared`: rescore a run from its folder on a split shared with others.

A run folder holds what its scores were built from: `scores.log` names the data, the experiment,
each holdout's split and each arm's rows by sha256, and `holdout-candidates.jsonl` holds every row
a BKO arm kept. `rescore` scores the folder's run again through `bko.evaluate.run.score_holdout`:
each BKO arm is a `StoredArm` that returns its last returned attempt's `kept` lines, grouped by
each row's own cell in the request's grid order, and counts its candidates from the file; each
baseline is regenerated by its runner. With `--with` folders, their BKO arms' gap and replica rows
are rebuilt the same way and passed as `exclude`, so every record any of the runs copies leaves
the test split and each holdout writes a `shared-split` row (`bko.evaluate.shared_split`). Their
baselines' rows are the folder's own, which identity check 5 holds, so they exclude nothing more.

Seven identity checks hold or the command stops with `IdentityError` (exit 3); ADR
`research/shared-test-split-reading` lists them. A missing file is an `OSError` (exit 2).
"""

